"""Synchronize and clean the 9 A100V0 relaxation tests (3 loading rates x 3
reps). Like the preliminary A100V0-test-relax test, this specimen's
built-in extensometer channel ("Ch:Strain_Orig") is garbage (huge
nonsensical values), so strain instead comes from the two-point
videoextensometer (../../tools/dogbone-videoextensometer), tracked at the
SAME pixel coordinates -- (150, 355) and (400, 355) -- confirmed on test 1
and reused unchanged on every other test, per
D30A1974_extensometer.csv..D30A1982_extensometer.csv (already generated by
running videoextensometer.py's `track` subcommand on each of the 9 raw
.MOV files in this directory).

Originally tracked at (200, 355)/(500, 355). Same issue found for A75V25
(see A75V25-relax/sync_and_clean_data.py's docstring): almost all real
elongation shows up as drift of the right point in camera-frame terms,
and at this material's ~30-37% engineering strain the original right
point drifted far enough to approach its shoulder, with strain plateauing
before the machine ramp actually ended (as early as ~95% of the way
through, across the original 9 tests). Re-tracked at the coordinates
above, with more margin before the shoulder; freeze point across all 9
tests moved from 95-98% to 95-99% of the ramp -- a smaller improvement
than A75V25's, since the original placement here already had more margin
relative to how far this material's points actually drift.

Unlike the preliminary test, the video's frame rate IS known exactly from
each file's own container metadata (59.9401 fps, confirmed identical
across all 9 recordings), so synchronization only needs to solve for ONE
unknown per test -- the time offset t0 between video frame 0 and the
machine's t=0 -- not fps itself. t0 is found the same way as the
preliminary test: match the video's own ramp onset (in frame-index units,
via find_ramp_bounds on the tracked strain trace) against the machine's
ramp onset (in time, via find_ramp_bounds on Ch:Position), assuming the
specimen's actual strain onset coincides with the crosshead's commanded
ramp onset.

Like every other material in this project, each test's raw machine CSV is
split into multiple chunks by the acquisition software once a file gets
large enough -- the base file (e.g. "A100V0-1_..._192156.csv") plus
"_1", "_2", ... continuations with contiguous Time (sec) values. Missing
this the first time round silently truncated every test to its first
chunk only (~250s), making the recorded hold look like a ~250s test
rather than the actual ~600s (~720s for the "very slow" group, whose
~119s ramp is added on top) -- load_relax_chunks() below concatenates
all of them, the same way the other materials' clean_data.py already
does.

Video-measured strain is only trustworthy for the loading ramp: the
recordings do not cover the full ~600-720s test (most stop well into the
hold, and were only ever tracked out to a generous margin past the ramp
-- see the end-frame choice when `track` was run), and even where they
do extend further, tracking noise accumulates over a much longer window
than it was validated against. To support relaxation/Prony fitting (which
needs the full hold), each cleaned file now covers the ENTIRE machine
test duration, with strain equal to the video-tracked value up through
the machine's own ramp-end time, then held CONSTANT (frozen at that
ramp-end value) for the rest of the hold -- i.e. engineering strain is
assumed constant during relaxation, matching the crosshead being
position-held (fixed grip separation) for that phase. This ignores any
real local creep at the gauge during hold (a second-order effect noted
for other materials' extensometer data -- see fit_bb_model.py's
docstring), which is a real but presumably small approximation, not
measured here.

Force sign convention: like the preliminary test, this real dataset's raw
Ch:Load is POSITIVE in tension (unlike every other *-relax raw file in
this project, where Ch:Load is negative in tension and the shared load()
helper in fit_qlv_model.py negates it) -- so this script negates it on the
way into the cleaned csv, keeping the cleaned-file sign convention
(force_N negative-in-tension) identical across all materials.
"""

from pathlib import Path

import numpy as np
import pandas as pd

RAW_DIR = Path(__file__).parent
CLEANED_DIR = RAW_DIR / "cleaned"

POSITION_STEP_MM = 0.0002
STRAIN_STEP = 0.01

TESTS = {
    1: ("A100V0-1_09042026_192156.csv", "D30A1974"),
    2: ("A100V0-2_09042026_194209.csv", "D30A1975"),
    3: ("A100V0-3_09042026_200533.csv", "D30A1976"),
    4: ("A100V0-4_09042026_202016.csv", "D30A1977"),
    5: ("A100V0-5_09042026_203321.csv", "D30A1978"),
    6: ("A100V0-6_09042026_204919.csv", "D30A1979"),
    7: ("A100V0-7_09042026_210354.csv", "D30A1980"),
    8: ("A100V0-8_09042026_211820.csv", "D30A1981"),
    9: ("A100V0-9_09042026_213339.csv", "D30A1982"),
}

FPS = 59.9401


def find_ramp_bounds(x, step_threshold):
    """Same onset/end detection used throughout this project (fit_qlv_model.py,
    clean_data.py, the preliminary A100V0-test-relax script), applied
    identically to the machine's position trace (mm, time-indexed) and the
    video's tracked strain trace (dimensionless, frame-indexed)."""
    baseline = x[0]
    deviation = np.abs(x - baseline)
    sustained = pd.Series(deviation).rolling(5).min() > step_threshold
    nonzero = sustained.to_numpy().nonzero()[0]
    onset = max(nonzero[0] - 4, 0) if len(nonzero) else 0
    n = len(x)
    hold_value = np.median(x[-max(1, n // 10):])
    reached = np.nonzero(x >= 0.99 * hold_value)[0]
    candidates = reached[reached > onset]
    ramp_end = candidates[0] if len(candidates) else n - 1
    return onset, ramp_end


def load_relax_chunks(machine_name):
    """Concatenate a test's base raw CSV with its "_1", "_2", ... continuation
    chunks (contiguous Time (sec) values), the same pattern used by every
    other material's clean_data.py."""
    stem = machine_name[:-len(".csv")]
    chunks = [RAW_DIR / machine_name]
    n = 1
    while (chunk := RAW_DIR / f"{stem}_{n}.csv").exists():
        chunks.append(chunk)
        n += 1
    return pd.concat(
        [pd.read_csv(c, usecols=["Time (sec)", "Ch:Position (mm)", "Ch:Load (N)"]) for c in chunks],
        ignore_index=True,
    )


def process(test_id, machine_name, video_stem):
    machine = load_relax_chunks(machine_name)
    machine = machine.rename(columns={"Time (sec)": "time_s", "Ch:Position (mm)": "position_mm",
                                       "Ch:Load (N)": "load_N"})

    ext = pd.read_csv(RAW_DIR / f"{video_stem}_extensometer.csv")

    m_onset, m_ramp_end = find_ramp_bounds(machine["position_mm"].to_numpy(), POSITION_STEP_MM / 2)
    v_onset, v_ramp_end = find_ramp_bounds(ext["strain"].to_numpy(), STRAIN_STEP)

    t0 = machine["time_s"].iloc[m_onset] - ext["frame"].iloc[v_onset] / FPS
    ext["video_time_s"] = t0 + ext["frame"] / FPS

    machine_ramp_dur = machine["time_s"].iloc[m_ramp_end] - machine["time_s"].iloc[m_onset]
    video_ramp_dur = (ext["frame"].iloc[v_ramp_end] - ext["frame"].iloc[v_onset]) / FPS
    print(f"test {test_id} ({video_stem}): machine ramp [{machine['time_s'].iloc[m_onset]:.3f}, "
          f"{machine['time_s'].iloc[m_ramp_end]:.3f}]s (dur {machine_ramp_dur:.3f}s); "
          f"video ramp frames [{ext['frame'].iloc[v_onset]}, {ext['frame'].iloc[v_ramp_end]}] "
          f"(dur {video_ramp_dur:.3f}s); t0={t0:.3f}s")

    video_t_max = ext["video_time_s"].max()
    t_ramp_end = machine["time_s"].iloc[m_ramp_end]
    if t_ramp_end > video_t_max:
        print(f"  WARNING: video coverage ends at t={video_t_max:.3f}s, before the machine ramp end "
              f"({t_ramp_end:.3f}s) -- frozen strain will be extrapolated from the last covered "
              f"video sample instead of a genuine ramp-end value")

    # full test duration: interpolate video-tracked strain up through the
    # machine's ramp-end time, then hold it constant (np.interp clips to
    # the last x/y pair for any x beyond the given range, which is exactly
    # this freeze behavior once xp/fp are truncated at t_ramp_end).
    df = machine.reset_index(drop=True)
    ext_upto_ramp_end = ext[ext["video_time_s"] <= t_ramp_end]
    df["strain"] = np.interp(df["time_s"], ext_upto_ramp_end["video_time_s"], ext_upto_ramp_end["strain"])
    df["force_N"] = -df["load_N"]

    baseline = df[["position_mm", "force_N", "strain"]].iloc[:m_onset].mean()
    df[["position_mm", "force_N", "strain"]] = df[["position_mm", "force_N", "strain"]] - baseline

    out = df[["time_s", "position_mm", "force_N", "strain"]]
    out_path = CLEANED_DIR / f"A100V0-{test_id}_cleaned.csv"
    out.to_csv(out_path, index=False)
    print(f"  saved {len(out)} rows (t in [{out['time_s'].iloc[0]:.3f}, {out['time_s'].iloc[-1]:.3f}]s), "
          f"peak strain {out['strain'].max():.4f}, frozen from t={t_ramp_end:.3f}s -> {out_path}")


def main():
    CLEANED_DIR.mkdir(exist_ok=True)
    for test_id, (machine_name, video_stem) in TESTS.items():
        process(test_id, machine_name, video_stem)


if __name__ == "__main__":
    main()
