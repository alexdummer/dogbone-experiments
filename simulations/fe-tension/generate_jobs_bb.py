"""Generate the 5 per-material EdelweissFE job decks for the dogbone-lattice
relaxation-test simulations, using the fitted Bergstrom-Boyce (Arruda-Boyce
network) model instead of QLV-Marmot. Companion to generate_jobs.py, which
this mirrors closely -- same shared mesh, same measured mid-rate protocol
per material, only the material model differs.

Each material uses:
  - the shared all-hex lattice mesh (lattice_mesh.inc, from mesh_lattice.py)
  - its fitted Marmot BergstromBoyce (Arruda-Boyce networks) parameters, from
    dogbone-relaxation/bb_params.csv
  - its own "mid" (slow rate-group) relaxation-test protocol, identical to
    generate_jobs.py's (same test id, same ramp/hold durations/displacement)

Jobs are written to {material}_bb/ subdirectories (distinct from
generate_jobs.py's {material}/) so the two models' outputs never collide.

BergstromBoyce's property vector (13 slots, from Marmot's
BergstromBoyce.h/.cpp and the Python bindings in fit_bb_model.py -- there is
no onlyShearCreep flag and no Maxwell/Prony branch count for this material,
unlike CompressibleFiniteStrainLinearViscoelasticity):
  hyperelasticBase(3=ArrudaBoyce), kappaA, kappaB, A1, A2, A3, B1, B2, B3,
  c1, c2, c3, implementationType(0=CSDA, the only implemented option)
"""
import csv
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT))
from fit_qlv_model import MATERIALS, load, find_ramp_bounds  # noqa: E402

HERE = Path(__file__).parent
PARAMS_CSV = REPO_ROOT / "simulations" / "material-calibration" / "parameters" / "bb_params.csv"

ARRUDA_BOYCE_BASE_ID = 3  # BergstromBoyce's OWN HyperelasticBase enum (0-3),
# distinct from CompressibleFiniteStrainLinearViscoelasticity's unrelated
# 5-way selector -- do NOT reuse generate_jobs.py's BASE_MODEL_ID here.


def load_bb_params():
    params = {}
    with open(PARAMS_CSV) as f:
        for row in csv.DictReader(f):
            assert row["hyperelastic_base"] == "ArrudaBoyce"
            params[row["material"]] = row
    return params


def mid_rate_protocol(material, cfg):
    """Identical to generate_jobs.py's -- same measured mid-rate protocol,
    so the two models' predictions are directly comparable."""
    test_id = cfg["rate_groups"]["slow"][0]
    df = load(cfg, material, test_id)
    onset, ramp_end = find_ramp_bounds(df["position_mm"])
    t = df["time_s"].to_numpy()
    pos = df["position_mm"].to_numpy()
    t_ramp = t[ramp_end] - t[onset]
    u_final = pos[ramp_end] - pos[onset]
    t_hold = t[-1] - t[onset] - t_ramp
    return t_ramp, u_final, t_hold, test_id


def render_job(material, params_row, t_ramp, u_final, t_hold, test_id, mesh_include_path, nudge=0.0):
    kappaA = float(params_row["kappaA"])
    kappaB = float(params_row["kappaB"])
    A1, A2, A3 = (float(params_row[k]) for k in ("A1", "A2", "A3"))
    B1, B2, B3 = (float(params_row[k]) for k in ("B1", "B2", "B3"))
    c1, c2, c3 = (float(params_row[k]) for k in ("c1", "c2", "c3"))
    # BergstromBoyce's Newton-Raphson return-mapping has a narrow,
    # seed-sensitive convergence failure mode for isolated parameter
    # combinations (CLAUDE.md; also why fit_bb_model.py's simulate_bb()
    # retries with small nudges to A/B/c1 rather than treating it as a real
    # divergence) -- apply the same style of nudge here if the un-nudged FE
    # run hits it (observed: NaN in the linear solve at the zero increment).
    scale = 1.0 + nudge
    A1, A2, A3 = A1 * scale, A2 * scale, A3 * scale
    B1, B2, B3 = B1 * scale, B2 * scale, B3 * scale
    c1 = c1 * scale

    return f"""\
** Dogbone-lattice stress-relaxation simulation for material {material}.
** Auto-generated by generate_jobs_bb.py -- do not hand-edit; regenerate instead.
**
** Mesh: lattice_mesh.inc (shared across all 5 materials, from mesh_lattice.py).
** Material: Marmot BergstromBoyce, Arruda-Boyce networks, fitted parameters
** from dogbone-relaxation/bb_params.csv. Companion run to generate_jobs.py's
** QLV-Marmot (Mooney-Rivlin) job for the same material/protocol.
** Protocol: {material}'s own "mid" (slow-rate-group) relaxation test, test id
** {test_id} -- ramp to the measured grip displacement over the measured ramp
** duration, then hold for the measured remaining test duration.
**
** Mesh is the x>=0/y>=0/z<=T/2 octant only (mirror symmetry, see
** mesh_lattice.py): the moving grip is displaced by u_final/2, equivalent by
** symmetry to the physical test's "one grip fixed, other moves by u_final".
**
** This job lives in its own {material}_bb/ subdirectory so its ensight/CSV
** outputs don't collide with generate_jobs.py's QLV-Marmot run for the same
** material -- only the mesh include is shared, hence the absolute path below.

*include, input={mesh_include_path}

*material, name=BergstromBoyce, id=bb{material}
** hyperelasticBase(3=ArrudaBoyce), kappaA, kappaB
{ARRUDA_BOYCE_BASE_ID}, {kappaA:.10g}, {kappaB:.10g},
** A1, A2, A3, B1, B2, B3
{A1:.10g}, {A2:.10g}, {A3:.10g}, {B1:.10g}, {B2:.10g}, {B3:.10g},
** c1, c2, c3, implementationType(0=CSDA)
{c1:.10g}, {c2:.10g}, {c3:.10g}, 0

*section, name=section1, material=bb{material}, type=solid
all

*job, name={material}_bb_relax, domain=3d
*solver, solver=NISTParallel, name=theSolver

*fieldOutput
>>perNode, name=displacement, elSet=all, field=displacement, result=U
>>perElement, name=stress, elSet=all, result=stress, quadraturePoint=0:8, f(x)='np.mean(x,axis=1)'
>>perNode, name=gripDisp, nSet=movingGrip, field=displacement, result=U, f(x)='np.mean(x[:,0])', saveHistory=True, export=gripDisp
>>perNode, name=gripForce, nSet=movingGrip, field=displacement, result=P, f(x)='np.sum(x[:,0])', saveHistory=True, export=gripForce

*output, type=ensight, name=ensightExport
>>perNode, fieldOutput=displacement
>>perElement, fieldOutput=stress
>>configuration, overwrite=yes

*output, type=monitor, name=mon
fieldOutput=gripForce

** Same increment scheme as generate_jobs.py's QLV jobs (see comments there):
** startInc/maxInc target ~20 increments per step, minInc kept small so the
** solver can cut back if a step doesn't converge on the first try. Per
** CLAUDE.md, BergstromBoyce's return-mapping has a narrow, seed-sensitive
** convergence failure mode for isolated parameter combinations (why
** fit_bb_model.py multi-starts) -- this cutback margin is this FE run's only
** defense against that, since there is no multi-start equivalent here.

*step, solver=theSolver
startInc=0.05, maxInc=0.05, minInc=1e-6, maxNumInc=100000, maxIter=25, stepLength={t_ramp:.6g}
>>options, category=NISTSolver, extrapolation=linear, linsolver=pardiso
** BergstromBoyce's state (Fv, the network-B viscous deformation gradient)
** must be initialized to the identity, not left at EdelweissFE's generic
** all-zeros default -- a zero Fv is singular (Fastor::inverse(Fv) at the
** very first, F=I zero-increment check), which produced a NaN in the
** linear solve regardless of the BergstromBoyce.h residual fix (see
** commit fixing computeResidualVector's dT division) until this was added.
>>initializematerial, name=initMat
>>dirichlet, name=xsym, nSet=xSymmetry, field=displacement, 1=0
>>dirichlet, name=ysym, nSet=ySymmetry, field=displacement, 2=0
>>dirichlet, name=zsym, nSet=zSymmetry, field=displacement, 3=0
>>dirichlet, name=fixmove, nSet=movingGrip, field=displacement, 2=0, 3=0
>>dirichlet, name=ramp, nSet=movingGrip, field=displacement, 1={u_final / 2:.6g}

*step, solver=theSolver
startInc=0.05, maxInc=0.05, minInc=1e-6, maxNumInc=100000, maxIter=25, stepLength={t_hold:.6g}
>>options, category=NISTSolver, extrapolation=linear, linsolver=pardiso
"""


def main():
    # Per-material nudge overrides (see render_job's docstring comment): only
    # needed as a last resort if a material still hits the narrow, seed-
    # sensitive Newton-Raphson convergence failure mode documented in
    # CLAUDE.md/fit_bb_model.py, mid-simulation (NOT the zero-increment NaN,
    # which is now fixed at the source -- see BergstromBoyce.h's
    # computeResidualVector).
    NUDGE_OVERRIDE = {}

    bb_params = load_bb_params()
    mesh_include_path = str((HERE / "mesh" / "lattice_mesh.inc").resolve())
    for material, cfg in MATERIALS.items():
        t_ramp, u_final, t_hold, test_id = mid_rate_protocol(material, cfg)
        nudge = NUDGE_OVERRIDE.get(material, 0.0)
        text = render_job(material, bb_params[material], t_ramp, u_final, t_hold, test_id,
                           mesh_include_path, nudge=nudge)
        material_dir = HERE / "jobs" / f"{material}_bb"
        material_dir.mkdir(parents=True, exist_ok=True)
        out_path = material_dir / f"{material}_bb_relax.inp"
        out_path.write_text(text)
        print(f"wrote {out_path.relative_to(HERE)}: t_ramp={t_ramp:.4f}s u_final={u_final:.4f}mm "
              f"t_hold={t_hold:.3f}s (test {test_id}) nudge={nudge:+.4g}")


if __name__ == "__main__":
    main()
