"""Generate the 5 per-material EdelweissFE job decks for the dogbone-lattice
relaxation-test simulations.

Each material uses:
  - the shared all-hex lattice mesh (lattice_mesh.inc, from mesh_lattice.py)
  - its fitted QLV-Marmot Mooney-Rivlin + 3-term Prony parameters, from
    dogbone-relaxation/qlv_marmot_params.csv
  - its own "mid" (slow rate-group) relaxation-test protocol (ramp duration,
    final grip displacement, hold duration), computed from that material's
    actual cleaned test data via the same find_ramp_bounds() used by
    fit_qlv_model.py

Two *step blocks reproduce the physical test: a displacement-ramp step to the
measured grip displacement over the measured ramp duration, then a hold step
(no new Dirichlet action -> EdelweissFE holds the last-reached displacement
constant) for the measured hold duration, letting the material relax.
"""
import csv
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT))
from fit_qlv_model import MATERIALS, load, find_ramp_bounds  # noqa: E402

HERE = Path(__file__).parent
PARAMS_CSV = REPO_ROOT / "simulations" / "material-calibration" / "parameters" / "qlv_marmot_params.csv"

BASE_MODEL_ID = {"NeoHooke": 0, "Yeoh": 1, "MooneyRivlin": 2, "ArrudaBoyce": 4, "Ogden": 5}


def load_qlv_params():
    params = {}
    with open(PARAMS_CSV) as f:
        for row in csv.DictReader(f):
            if row["hyperelastic_base"] != "MooneyRivlin":
                continue
            params[row["material"]] = row
    return params


def mid_rate_protocol(material, cfg):
    """Ramp duration/final displacement/hold duration for the material's
    'slow' (mid, of very-slow/slow/fast) rate-group representative test,
    using the actual measured grip position (not strain)."""
    test_id = cfg["rate_groups"]["slow"][0]
    df = load(cfg, material, test_id)
    onset, ramp_end = find_ramp_bounds(df["position_mm"])
    t = df["time_s"].to_numpy()
    pos = df["position_mm"].to_numpy()
    t_ramp = t[ramp_end] - t[onset]
    u_final = pos[ramp_end] - pos[onset]
    t_hold = t[-1] - t[onset] - t_ramp
    return t_ramp, u_final, t_hold, test_id


def render_job(material, params_row, t_ramp, u_final, t_hold, test_id, mesh_include_path):
    C10 = float(params_row["C1"])
    C01 = float(params_row["C2"])
    kappa = float(params_row["K"])
    gammas = [float(params_row[f"gamma{i}"]) for i in (1, 2, 3)]
    taus = [float(params_row[f"tau{i}"]) for i in (1, 2, 3)]

    maxwell_lines = "\n".join(f"{g:.10g}, {t:.10g}," for g, t in zip(gammas, taus))

    return f"""\
** Dogbone-lattice stress-relaxation simulation for material {material}.
** Auto-generated by generate_jobs.py -- do not hand-edit; regenerate instead.
**
** Mesh: lattice_mesh.inc (shared across all 5 materials, from mesh_lattice.py).
** Material: Marmot CompressibleFiniteStrainLinearViscoelasticity, Mooney-Rivlin
** base, fitted parameters from dogbone-relaxation/qlv_marmot_params.csv (QLV-Marmot,
** this project's reported/primary model per CLAUDE.md).
** Protocol: {material}'s own "mid" (slow-rate-group) relaxation test, test id
** {test_id} -- ramp to the measured grip displacement over the measured ramp
** duration, then hold for the measured remaining test duration.
**
** Mesh is the x>=0/y>=0/z<=T/2 octant only (mirror symmetry, see
** mesh_lattice.py): the moving grip is displaced by u_final/2, equivalent by
** symmetry to the physical test's "one grip fixed, other moves by u_final".
**
** This job lives in its own {material}/ subdirectory so its ensight/CSV
** outputs (all written relative to the working directory EdelweissFE is run
** from) don't collide with the other materials' -- only the mesh include is
** shared, hence the absolute path below.

*include, input={mesh_include_path}

*material, name=CompressibleFiniteStrainLinearViscoelasticity, id=qlv{material}
** baseModel(2=MooneyRivlin), onlyShearCreep, C10, C01, kappa,
2, 1,
{C10:.10g}, {C01:.10g}, {kappa:.10g},
** nMaxwell, (gamma_i, tau_i) x 3
3,
{maxwell_lines}

*section, name=section1, material=qlv{material}, type=solid
all

*job, name={material}_relax, domain=3d
*solver, solver=NISTParallel, name=theSolver

*fieldOutput
>>perNode, name=displacement, elSet=all, field=displacement, result=U
>>perElement, name=stress, elSet=all, result=stress, quadraturePoint=0:8, f(x)='np.mean(x,axis=1)'
** Grip axial displacement (mm) and total reaction force (N) at every
** increment, for force-time / force-displacement postprocessing. Both are
** written every increment (time is prepended automatically) to
** gripDisp.csv / gripForce.csv in this job's own {material}/ directory.
** gripDisp is the (uniform, prescribed) x-displacement of the movingGrip
** nSet; gripForce is the sum of the x-component of "P" (the solver's nodal
** force vector) there. Verified (A0V100) unflipped: ramps 0->48.8N then
** relaxes to 32.4N over the hold, positive throughout -- matches this
** codebase's own reaction-force convention (testfiles/marmot/
** LinearElasticIsotropic/test.inp's ">>perNode, name=RF_left, ...,
** result=P, f(x)='np.sum(x[:,1])'", no sign flip).
>>perNode, name=gripDisp, nSet=movingGrip, field=displacement, result=U, f(x)='np.mean(x[:,0])', saveHistory=True, export=gripDisp
>>perNode, name=gripForce, nSet=movingGrip, field=displacement, result=P, f(x)='np.sum(x[:,0])', saveHistory=True, export=gripForce

*output, type=ensight, name=ensightExport
>>perNode, fieldOutput=displacement
>>perElement, fieldOutput=stress
>>configuration, overwrite=yes

*output, type=monitor, name=mon
fieldOutput=gripForce

** NOTE: maxInc/minInc/startInc are FRACTIONS of stepLength (0..1), not
** absolute time -- startInc defaults to 1.0 (try the whole step first), so
** it must be set explicitly too or the solver jumps straight to the end of
** the step whenever that happens to converge (which it always does for the
** hold step, since Marmot's exponential-update viscoelastic integrator is
** unconditionally stable regardless of dt).

*step, solver=theSolver
** targets 20 increments (startInc=maxInc=0.05), but keeps minInc small so
** the solver can still cut back if a 5%-of-ramp jump doesn't converge
** (unlike the hold step, large-displacement materials may need this).
startInc=0.05, maxInc=0.05, minInc=1e-4, maxNumInc=100000, maxIter=25, stepLength={t_ramp:.6g}
>>options, category=NISTSolver, extrapolation=linear, linsolver=pardiso
>>dirichlet, name=xsym, nSet=xSymmetry, field=displacement, 1=0
>>dirichlet, name=ysym, nSet=ySymmetry, field=displacement, 2=0
>>dirichlet, name=zsym, nSet=zSymmetry, field=displacement, 3=0
>>dirichlet, name=fixmove, nSet=movingGrip, field=displacement, 2=0, 3=0
>>dirichlet, name=ramp, nSet=movingGrip, field=displacement, 1={u_final / 2:.6g}

*step, solver=theSolver
** targets 20 equal increments (startInc=maxInc=0.05), so the hold step
** actually samples the relaxation curve instead of converging in a single
** full-step jump; minInc is kept small (not also 0.05) so the solver can
** still cut back if a 5%-of-hold jump doesn't converge on the first try
** (A100V0's large displacement/soft material needed this: its first hold
** increment failed to converge with no room to shrink when minInc was
** rigidly pinned to 0.05 too).
startInc=0.05, maxInc=0.05, minInc=1e-4, maxNumInc=100000, maxIter=25, stepLength={t_hold:.6g}
>>options, category=NISTSolver, extrapolation=linear, linsolver=pardiso
"""


def main():
    qlv_params = load_qlv_params()
    mesh_include_path = str((HERE / "mesh" / "lattice_mesh.inc").resolve())
    for material, cfg in MATERIALS.items():
        t_ramp, u_final, t_hold, test_id = mid_rate_protocol(material, cfg)
        text = render_job(material, qlv_params[material], t_ramp, u_final, t_hold, test_id,
                           mesh_include_path)
        material_dir = HERE / "jobs" / material
        material_dir.mkdir(parents=True, exist_ok=True)
        out_path = material_dir / f"{material}_relax.inp"
        out_path.write_text(text)
        print(f"wrote {out_path.relative_to(HERE)}: t_ramp={t_ramp:.4f}s u_final={u_final:.4f}mm "
              f"t_hold={t_hold:.3f}s (test {test_id})")


if __name__ == "__main__":
    main()
