"""Synchronize and clean the A75V25 relaxation tests. As with A100V0, this
specimen's built-in extensometer channel ("Ch:Strain (in/in)") is garbage
(huge nonsensical values, e.g. millions of "in/in"), so strain instead
comes from the two-point videoextensometer (../../tools/dogbone-
videoextensometer), per D30A198x/D30A199x_extensometer.csv (already
generated by running videoextensometer.py's `track` subcommand on each
raw .MOV file in the 2026_09_07/ subfolder -- new data drops for this
material are expected to land in their own dated subfolder as they
arrive, unlike the other materials' flat layout).

Track points are chosen INDIVIDUALLY per test via videoextensometer.py's
`autopoints` subcommand (image-processing boundary detection: the
specimen mask's width(x) profile finds the longest, narrowest, genuinely
flanked-by-shoulders-on-both-sides flat run -- see that subcommand's own
docstring), not one fixed pixel pair reused across every test. A fixed
pair was tried first (originally (370,275)/(970,275), then widened to
(400,275)/(800,275)) and rejected: confirmed directly (comparing pt1/pt2
drift, not assumed) that almost all real elongation shows up as drift of
the right point in camera-frame terms, and at this material's ~8-10%
engineering strain a fixed right point can drift right up against where
the shoulder fillet visibly starts curving -- past which there's
essentially no more local motion to track, so strain plateaus well
before the machine ramp actually ends. This was not a synchronization
bug (a 2x larger LK search window made no difference) or a video-
coverage problem (video_time_s comfortably exceeds the machine ramp end
in every case this affected) -- purely a placement-margin issue, and
different tests drift different amounts, so no single fixed pair has
enough margin for all of them. Per-test auto-detected points push the
freeze point (fraction of the ramp before strain stops updating) to
90-100% for 8 of the 9 tests, several essentially perfect (99.9%). Test
8 is the remaining outlier (freezes at ~82%) -- that one's a genuine
video-coverage shortfall (see the WARNING below), not a placement issue,
and isn't fixable by re-tracking the same footage.

This is the full dataset: all 9 of the eventual 9 tests (3 loading rates x 3
reps) are usable. Tests 1-3 share one ramp rate (~29.7s ramp, "slow" tier,
complete at n=3); tests 4-6 are a second, faster rate (~2.99s ramp, "fast"
tier, complete at n=3, test 6's video D30A1989 confirmed by creation-time
offset -- 20:08:08 UTC vs. the predicted 20:08:10 -- matching every other
test's very consistent ~1:26:xx machine-to-video offset); tests 7-9 are
the "very slow" tier (~148.5s ramp -- notably only ~5x slower than "slow",
not the ~10x spacing used elsewhere in this project, an intentional
choice for this material apparently). Test 7's original video (D30A1991.MOV)
was corrupted -- confirmed via direct cv2 frame-by-frame probing: the vast
majority of its frames failed to decode ("partial file" errors), not just
an isolated glitch -- so "very slow" was n=2 (tests 8-9) until the video was
re-transferred; the replacement tracks cleanly start-to-end (no unreadable
frames, max forward-backward error 0.041px), so "very slow" is now n=3. See
videoextensometer.py's own MAX_UNREADABLE_FRACTION safeguard, added after
this file's original corruption was initially masked by carrying a frozen
(wrong) strain value forward across nearly the entire recording.

Unlike A100V0, this specimen's raw Ch:Load is already NEGATIVE in tension
(confirmed directly: -43.7N at mid-ramp), the same convention as every
other *-relax raw file in this project except A100V0 -- so, unlike
A100V0's sync script, force is NOT negated here, matching clean_data.py's
plain rename for A0V100/A25V75/A50V50.

Video-measured strain is only trustworthy for the loading ramp (see
A100V0-relax/sync_and_clean_data.py's docstring for the full reasoning,
which applies identically here): each cleaned file covers the ENTIRE
machine test duration, with strain equal to the video-tracked value up
through the machine's own ramp-end time, then held CONSTANT for the rest
of the hold.

Like every other material in this project, each test's raw machine CSV is
split into multiple chunks ("_1", "_2", ...) once a file gets large enough
-- load_relax_chunks() below concatenates all of them.
"""

from pathlib import Path

import numpy as np
import pandas as pd

RAW_DIR = Path(__file__).parent
CLEANED_DIR = RAW_DIR / "cleaned"

POSITION_STEP_MM = 0.0002
STRAIN_STEP = 0.01

# test_id -> (machine csv base filename, video stem)
TESTS = {
    1: ("A75V25-1_09072026_172701.csv", "D30A1984"),
    2: ("A75V25-2_09072026_174048.csv", "D30A1985"),
    3: ("A75V25-3_09072026_175510.csv", "D30A1986"),
    4: ("A75V25-4_09072026_181334.csv", "D30A1987"),
    5: ("A75V25-5_09072026_182722.csv", "D30A1988"),
    6: ("A75V25-6_09072026_184157.csv", "D30A1989"),
    7: ("A75V25-7-real_09072026_190631.csv", "D30A1991"),
    8: ("A75V25-8_09072026_192212.csv", "D30A1992"),
    9: ("A75V25-9_09072026_193826.csv", "D30A1993"),
}

FPS = 59.9401


def find_ramp_bounds(x, step_threshold):
    """Same onset/end detection used throughout this project (fit_qlv_model.py,
    clean_data.py, A100V0-relax/sync_and_clean_data.py), applied identically
    to the machine's position trace (mm, time-indexed) and the video's
    tracked strain trace (dimensionless, frame-indexed)."""
    baseline = x[0]
    deviation = np.abs(x - baseline)
    sustained = pd.Series(deviation).rolling(5).min() > step_threshold
    nonzero = sustained.to_numpy().nonzero()[0]
    onset = max(nonzero[0] - 4, 0) if len(nonzero) else 0
    n = len(x)
    hold_value = np.median(x[-max(1, n // 10):])
    reached = np.nonzero(x >= 0.99 * hold_value)[0]
    candidates = reached[reached > onset]
    ramp_end = candidates[0] if len(candidates) else n - 1
    return onset, ramp_end


def load_relax_chunks(machine_name):
    """Concatenate a test's base raw CSV with its "_1", "_2", ... continuation
    chunks (contiguous Time (sec) values), the same pattern used by every
    other material's clean_data.py."""
    stem = machine_name[:-len(".csv")]
    chunks = [RAW_DIR / machine_name]
    n = 1
    while (chunk := RAW_DIR / f"{stem}_{n}.csv").exists():
        chunks.append(chunk)
        n += 1
    return pd.concat(
        [pd.read_csv(c, usecols=["Time (sec)", "Ch:Position (mm)", "Ch:Load (N)"]) for c in chunks],
        ignore_index=True,
    )


def process(test_id, machine_name, video_stem):
    machine = load_relax_chunks(machine_name)
    machine = machine.rename(columns={"Time (sec)": "time_s", "Ch:Position (mm)": "position_mm",
                                       "Ch:Load (N)": "force_N"})

    ext = pd.read_csv(RAW_DIR / f"{video_stem}_extensometer.csv")

    m_onset, m_ramp_end = find_ramp_bounds(machine["position_mm"].to_numpy(), POSITION_STEP_MM / 2)
    v_onset, v_ramp_end = find_ramp_bounds(ext["strain"].to_numpy(), STRAIN_STEP)

    t0 = machine["time_s"].iloc[m_onset] - ext["frame"].iloc[v_onset] / FPS
    ext["video_time_s"] = t0 + ext["frame"] / FPS

    machine_ramp_dur = machine["time_s"].iloc[m_ramp_end] - machine["time_s"].iloc[m_onset]
    video_ramp_dur = (ext["frame"].iloc[v_ramp_end] - ext["frame"].iloc[v_onset]) / FPS
    print(f"test {test_id} ({video_stem}): machine ramp [{machine['time_s'].iloc[m_onset]:.3f}, "
          f"{machine['time_s'].iloc[m_ramp_end]:.3f}]s (dur {machine_ramp_dur:.3f}s); "
          f"video ramp frames [{ext['frame'].iloc[v_onset]}, {ext['frame'].iloc[v_ramp_end]}] "
          f"(dur {video_ramp_dur:.3f}s); t0={t0:.3f}s")

    video_t_max = ext["video_time_s"].max()
    t_ramp_end = machine["time_s"].iloc[m_ramp_end]
    if t_ramp_end > video_t_max:
        print(f"  WARNING: video coverage ends at t={video_t_max:.3f}s, before the machine ramp end "
              f"({t_ramp_end:.3f}s) -- frozen strain will be extrapolated from the last covered "
              f"video sample instead of a genuine ramp-end value")

    df = machine.reset_index(drop=True)
    ext_upto_ramp_end = ext[ext["video_time_s"] <= t_ramp_end]
    df["strain"] = np.interp(df["time_s"], ext_upto_ramp_end["video_time_s"], ext_upto_ramp_end["strain"])

    baseline = df[["position_mm", "force_N", "strain"]].iloc[:m_onset].mean()
    df[["position_mm", "force_N", "strain"]] = df[["position_mm", "force_N", "strain"]] - baseline

    out = df[["time_s", "position_mm", "force_N", "strain"]]
    out_path = CLEANED_DIR / f"A75V25-{test_id}_cleaned.csv"
    out.to_csv(out_path, index=False)
    print(f"  saved {len(out)} rows (t in [{out['time_s'].iloc[0]:.3f}, {out['time_s'].iloc[-1]:.3f}]s), "
          f"peak strain {out['strain'].max():.4f}, frozen from t={t_ramp_end:.3f}s -> {out_path}")


def main():
    CLEANED_DIR.mkdir(exist_ok=True)
    for test_id, (machine_name, video_stem) in TESTS.items():
        process(test_id, machine_name, video_stem)


if __name__ == "__main__":
    main()
